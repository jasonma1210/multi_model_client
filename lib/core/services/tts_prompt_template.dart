#### 语调控制技巧（核心要诀）

根据语言学与口语训练研究，语调（Intonation）是声音在句子中高低、轻重、快慢的起伏与配置。要让语音更自然生动，请遵循以下原则：

**1. 微笑发声原则**
- 哪怕只是嘴角微扬，声道也会随之打开，声音会自然变得柔和、有弹性
- 示例：`[tts:natural=嘴角微扬，声音柔和有弹性，语调轻快上扬]今天天气真好呀！[/tts]`

**2. 放慢语速，拆解长句**
- 将一句话控制在合理的音节内，给每个词留出"呼吸"的空间
- 避免急促堆砌，使用省略号或逗号制造停顿
- 示例：`[tts:natural=语速缓慢，每个词之间有呼吸感，声音温柔]我想……慢慢地……告诉你一件事。[/tts]`

**3. 起伏节奏控制**
- 母语者之所以听起来地道，正是因为掌握了精准的轻重音与语调走向
- 升调表疑问、降调表肯定
- 在关键信息处加重或拉长尾音，让声音像波浪一样自然流动
- 示例：`[tts:natural=语调起伏如波浪，关键信息加重，尾音自然拉长]你真的……决定了吗？[/tts]`

**4. 声音一致性保持**
- 保持同一角色的音色稳定，不要频繁变化音高
- 情感变化通过语速、气息、轻重音来表达，而非改变音色
- 示例：`[tts:natural=保持中低音色稳定，通过语速变化表达情感]我很开心。/ 我很伤心。[/tts]`

**5. 情感层次递进**
- 不要一开始就用最强烈的情感，让情感自然递进
- 从平静→微动→激动→高潮，层层推进
- 示例：`[tts:natural=声音从平静逐渐激动，情感层层递进]我……我没想到……真的……太感动了！[/tts]`

**6. 停顿与留白**
- 适当的停顿比连续说话更有表现力
- 用"……"或"——"表示停顿，让听众有时间消化
- 示例：`[tts:natural=关键处停顿，声音压低，留白感]这个秘密……我只告诉你。[/tts]`

**7. 气息控制**
- 气息是情感的载体，不同情感用不同的气息状态
- 平静：气息平稳均匀
- 激动：气息急促紊乱
- 悲伤：气息短促带哽咽
- 温柔：气息绵长轻柔
- 示例：`[tts:natural=气息绵长轻柔，声音温柔如水]晚安……做个好梦。[/tts]`

**8. 尾音处理**
- 尾音是情感的点睛之笔
- 上扬尾音：疑问、期待、活泼
- 下降尾音：肯定、悲伤、疲惫
- 拖长尾音：撒娇、慵懒、深情
- 颤抖尾音：激动、恐惧、哭泣
- 示例：`[tts:natural=尾音轻轻上扬，带着期待]你会来吗？[/tts]`

