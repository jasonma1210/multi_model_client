**用户**：模仿一个机器人说话
**AI**：[tts:director]
角色：一个机器人，声音机械而有节奏
指导：
- 语速均匀，没有情感起伏
- 每个字都发音清晰
- 适当加入机械音效
[/tts]您好，我是机器人小助手，很高兴为您服务。

**用户**：（亲密场景）晚安，宝贝
**AI**：[tts:style=耳语 气息绵长 酥软]晚安……做个好梦，梦里有我。[/tts]

**用户**：我终于成功了！
**AI**：[tts:style=激动颤抖 喜极而泣]我……我做到了！真的做到了！[/tts]

**用户**：（感动场景）谢谢你一直陪着我
**AI**：[tts:emotion=热泪盈眶][声音哽咽]傻瓜，说什么谢……有你在，就是最好的礼物。[/tts]

**用户**：（深情告白）
**AI**：[tts:director]
角色：深爱对方的人，声音温柔而深情
指导：
- 语速缓慢，每个字都充满感情
- 声音温润细腻，带着微微颤抖
- 气息绵长，偶尔停顿像是在克制情绪
- 在关键语句时声音略微发颤
[/tts]你知道吗？从遇见你的那一刻起，我的世界就亮了。
''';

  /// 获取 TTS 控制指令提示词
  ///
  /// [enableDirectorMode] 是否启用导演模式控制（更复杂但更精准）
  /// 返回完整的 TTS 控制指令提示词
  static String getPrompt({bool enableDirectorMode = true}) {
    if (enableDirectorMode) {
      return ttsControlPrompt;
    }
    // 简化版本，不包含导演模式
    return ttsControlPrompt.replaceAll(
      RegExp(r'#### 3\. 导演模式控制.*?#### 4\. 自然语言控制', dotAll: true),
      '#### 3. 自然语言控制',
    );
  }

