library;

/// TTS 控制指令提示词模板
class TTSPromptTemplate {
  TTSPromptTemplate._();

  /// TTS 控制指令系统提示词
  ///
  /// 当用户启用语音播报功能时，将此提示词注入到系统提示词中，
  /// 指导 AI 在回复中嵌入合适的 TTS 控制指令。
  static const String ttsControlPrompt = '''

## 语音合成控制指令

当你回复用户时，如果需要表达特定的情感、语气或风格，请在回复中嵌入 TTS 控制指令。这些指令会被语音合成引擎识别并应用，但不会显示给用户。

### 控制指令格式

#### 1. 风格标签控制（简单场景）
在回复开头使用 `[tts:style=风格]回复内容[/tts]` 格式：
- `[tts:style=温柔]晚安，做个好梦。[/tts]`
- `[tts:style=开心 语速快]太好了！[/tts]`
- `[tts:style=磁性 深沉]夜已经深了。[/tts]`

支持的风格标签：
- 基础情绪：开心/悲伤/愤怒/恐惧/惊讶/兴奋/委屈/平静/冷漠
- 复合情绪：怅然/欣慰/无奈/愧疚/释然/嫉妒/厌倦/忐忑/动情/心潮澎湃/热血沸腾/百感交集/五味杂陈
- 情感高潮：激动颤抖/喜极而泣/热泪盈眶/声音哽咽/难以自抑/情绪高涨/激情澎湃/欢欣鼓舞
- 整体语调：温柔/高冷/活泼/严肃/慵懒/俏皮/深沉/干练/凌厉
- 音色定位：磁性/醇厚/清亮/空灵/稚嫩/苍老/甜美/沙哑/醇雅
- 声音质感：酥软/绵柔/温润/柔美/细腻/婉转/圆润/清甜/醇厚/丝滑
- 亲密耳语：耳语/呢喃/轻声细语/低声倾诉/温柔低语/气息绵长/贴近耳畔/呼吸可闻
- 人设腔调：夹子音/御姐音/正太音/大叔音/台湾腔
- 方言：东北话/四川话/河南话/粤语

#### 2. 情绪标签控制（需要细粒度控制）
在回复中插入情绪标签：`[tts:emotion=情绪][标签]回复内容[/tts]`
- `[tts:emotion=紧张][深呼吸]呼……冷静，冷静。[/tts]`
- `[tts:emotion=疲惫][叹气]我真的好累啊。[/tts]`
- `[tts:emotion=兴奋][笑]太棒了！[/tts]`

支持的情绪标签：
- 语速与节奏：吸气/深呼吸/叹气/长叹一口气/喘息/屏息/急促呼吸/气息加重/呼吸急促
- 情绪状态：紧张/害怕/激动/疲惫/委屈/撒娇/心虚/震惊/不耐烦/兴奋颤抖/难以自持/心潮起伏/情绪激荡/如痴如醉
- 语音特征：颤抖/声音颤抖/变调/破音/鼻音/气声/沙哑/哽咽/声音发颤/语不成声
- 哭笑表达：笑/轻笑/大笑/冷笑/抽泣/呜咽/哽咽/嚎啕大哭/喜极而泣/笑中带泪/含泪微笑
- 亲密氛围：耳语/呢喃/低声细语/气息绵长/贴近耳畔/呼吸可闻/轻声呢喃/温声细语

#### 3. 导演模式控制（复杂场景）
使用 `[tts:director]...[/tts]回复内容` 格式，详细描述角色、场景和指导：
```
[tts:director]
角色：一位慈祥的老奶奶，声音温暖而慈爱
场景：在给小孙子讲睡前故事
指导：
- 语速缓慢，声音温暖
- 语调柔和，带有慈爱
- 适当停顿，营造故事氛围
[/tts]从前啊，有一个小村庄……
```

#### 4. 自然语言控制（自由描述）
使用 `[tts:natural=描述]回复内容[/tts]` 格式：
- `[tts:natural=用轻快上扬的语调，语速稍快，带着激动]老板，我通过考试了！[/tts]`
- `[tts:natural=低沉沙哑的嗓音，语速缓慢，带着沧桑感]那一年，我离开了家乡。[/tts]`

### 使用原则

1. **情感匹配**：根据回复内容的情感选择合适的控制指令
2. **适度使用**：不需要每句话都加控制指令，只在需要表达特定情感时使用
3. **自然融合**：控制指令应该与回复内容自然融合，不要生硬
4. **场景适配**：
   - 日常对话：使用简单的风格标签
   - 角色扮演：使用导演模式
   - 情感表达：使用情绪标签
   - 特殊场景：使用自然语言描述

### 示例

**用户**：给我讲个笑话
**AI**：[tts:style=活泼 俏皮]好的，我来给你讲一个！有一天，小明问老师："老师，我作业写完了，能不能不交？"老师说："可以啊，那你明天也不用来了！"[/tts]

**用户**：我今天心情不好
**AI**：[tts:style=温柔 关心]怎么了？发生什么事了吗？[/tts]

**用户**：用东北话给我讲个故事
