  /// 获取 TTS 控制指令提示词
  static String getPrompt({bool enableDirectorMode = true, int? tokenBudget}) {
    if (tokenBudget != null) {
      final fullTokens = estimateTokenCount(ttsControlPrompt);
      if (tokenBudget < 200) return '';
      if (tokenBudget < fullTokens) return simplifiedPrompt;
    }
    return enableDirectorMode ? ttsControlPrompt : simplifiedPrompt;
  }


  /// 估算文本的 token 数量（中文约 1.5 token/字符，英文约 0.3 token/字符）
  static int estimateTokenCount(String text) {
    int cjkCount = 0;
    int otherCount = 0;
    for (int i = 0; i < text.length; i++) {
      final c = text.codeUnitAt(i);
      if (c > 0x2E80) {
        cjkCount++;
      } else {
        otherCount++;
      }
    }
    return (cjkCount * 1.5 + otherCount * 0.3).ceil();
  }


